#!/usr/bin/env python3
"""Build the website's pictures from the game's screenshots.

    python3 site/scripts/build-media.py

Reads screenshots (all captured in the game itself) from screenshots/, writes responsive WebP files
to site/public/media/<key>-<width>.webp, the social preview site/public/media/og.jpg, and the
manifest site/src/data/media.ts (sizes + a tiny blurred placeholder for each picture).
"""
import base64
import io
import json
import os

from PIL import Image, ImageFilter

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SHOTS = os.path.join(ROOT, 'screenshots')
OUT = os.path.join(ROOT, 'site', 'public', 'media')
MANIFEST = os.path.join(ROOT, 'site', 'src', 'data', 'media.ts')

# key: (source path under screenshots/, crop from the bottom as a fraction (cutscene captions))
SOURCES = {
    'water_whip': ('website/water_whip.jpg', 0),
    'octopus': ('website/octopus.jpg', 0),
    'water_spout': ('website/water_spout.jpg', 0),
    'rock_armor': ('website/rock_armor.jpg', 0),
    'earth_surf': ('website/earth_surf.jpg', 0),
    'dancing_dragon': ('website/dancing_dragon.jpg', 0),
    'fire_stream': ('website/fire_stream.jpg', 0),
    'lightning': ('website/lightning.jpg', 0),
    'air_scooter': ('website/air_scooter.jpg', 0),
    'avatar_state': ('website/avatar_state.jpg', 0),
    'elements_sphere': ('website/elements_sphere.jpg', 0),
    'place_nwt': ('website/place_nwt.jpg', 0),
    'place_bss': ('website/place_bss.jpg', 0),
    'place_fnc': ('website/place_fnc.jpg', 0),
    'place_sat': ('website/place_sat.jpg', 0),
    'nwt_canal_night': ('10_nwt_canal_night.jpg', 0),
    'nwt_oasis': ('08_nwt_spirit_oasis.jpg', 0),
    'sat_flocks': ('southern-air-temple/13_sky_flocks.jpg', 0),
    'sat_statues': ('southern-air-temple/12_statue_room_glowing.jpg', 0),
    'sat_dawn': ('southern-air-temple/14_dawn_takeoff.jpg', 0),
    'bss_train': ('ba-sing-se/11_train_on_viaduct.jpg', 0),
    'fnc_harbor': ('fire-nation-capital/00_harbor_approach_from_sea_wall.jpg', 0),
    'fnc_throne': ('fire-nation-capital/15_throne_room.jpg', 0),
    'ki_falls': ('kyoshi-island/crescent_bridge_and_crystal_falls.jpg', 0),
    'ki_beach': ('kyoshi-island/bay_beach_koi.jpg', 0),
    'bison': ('website/bison.jpg', 0),
    'swt_aurora': ('southern-water-tribe/16_festival_aurora.jpg', 0),
    'swt_lamps': ('southern-water-tribe/15_night_lamplight.jpg', 0),
    # Played on a phone: the game's touch layout, shown inside a phone frame on the site.
    'phone_hero': ('website/phone_hero.jpg', 0),
    'phone_water': ('website/phone_water.jpg', 0),
    'phone_earth': ('website/phone_earth.jpg', 0),
    'phone_fire': ('website/phone_fire.jpg', 0),
    'phone_air': ('website/phone_air.jpg', 0),
    'ki_village': ('website/ki_village.jpg', 0),
    'ki_hall': ('website/ki_hall.jpg', 0),
}

WIDTHS = [640, 1024, 1600]


def main() -> None:
    os.makedirs(OUT, exist_ok=True)
    manifest = {}
    for key, (rel, crop) in SOURCES.items():
        im = Image.open(os.path.join(SHOTS, rel)).convert('RGB')
        if crop:
            im = im.crop((0, 0, im.width, int(im.height * (1 - crop))))
        # Every listed width below the source (skipping near-duplicates of it), plus the source itself.
        widths = sorted({w for w in WIDTHS if w < im.width * 0.9} | {im.width})
        for w in widths:
            h = round(im.height * w / im.width)
            im.resize((w, h), Image.LANCZOS).save(os.path.join(OUT, f'{key}-{w}.webp'), 'WEBP', quality=80, method=6)
        tiny = im.resize((24, max(1, round(im.height * 24 / im.width))), Image.LANCZOS).filter(ImageFilter.GaussianBlur(0.6))
        buf = io.BytesIO()
        tiny.save(buf, 'WEBP', quality=50)
        manifest[key] = {
            'w': im.width,
            'h': im.height,
            'widths': widths,
            'lqip': 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode(),
        }
        print(key, im.size, widths)
    # Social preview (1200 × 630).
    og = Image.open(os.path.join(SHOTS, SOURCES['place_sat'][0])).convert('RGB')
    s = max(1200 / og.width, 630 / og.height)
    og = og.resize((round(og.width * s), round(og.height * s)), Image.LANCZOS)
    x0, y0 = (og.width - 1200) // 2, (og.height - 630) // 2
    og.crop((x0, y0, x0 + 1200, y0 + 630)).save(os.path.join(OUT, 'og.jpg'), quality=86, optimize=True)
    with open(MANIFEST, 'w') as f:
        f.write('/* Generated by site/scripts/build-media.py. Do not edit by hand. */\n')
        f.write('export interface MediaInfo {\n  w: number;\n  h: number;\n  widths: number[];\n  lqip: string;\n}\n\n')
        f.write('export const MEDIA: Record<string, MediaInfo> = ')
        f.write(json.dumps(manifest, indent=2).replace('"w"', 'w').replace('"h"', 'h').replace('"widths"', 'widths').replace('"lqip"', 'lqip'))
        f.write(';\n')


if __name__ == '__main__':
    main()
